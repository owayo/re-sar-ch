#[cfg(test)]
mod tests {
    use super::*;
    use crate::format::abi::{Endian, LayoutAbi};

    #[test]
    fn measured_fields_fit_saved_structures_on_both_abis() {
        for layout in LAYOUTS {
            for abi in [LayoutAbi::LP64, LayoutAbi::I386] {
                let enc = SourceEncoding::new(Endian::Little, abi);
                for (name, structure) in [
                    ("header", layout.header),
                    ("stats", layout.stats),
                    ("cpu", layout.cpu),
                    ("serial", layout.serial),
                    ("net", layout.net),
                    ("irqcpu", layout.irqcpu),
                    ("disk", layout.disk),
                    ("comment", layout.comment),
                ] {
                    for field in structure.fields {
                        if field.name.starts_with("pad") {
                            continue;
                        }
                        assert!(
                            field.at(&enc) + field.ty.value_width(&abi) <= structure.size,
                            "{:04x} {name}.{} exceeds saved size {} ({abi:?})",
                            layout.magic,
                            field.name,
                            structure.size
                        );
                    }
                }
            }
        }
    }
}
