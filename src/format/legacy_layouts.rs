use super::abi::SourceEncoding;
use super::wire::FieldTy;
use FieldTy::{Bytes, CULong, U8, U16, U32, U64};

#[derive(Clone, Copy, Debug)]
pub(crate) struct LegacyField {
    pub name: &'static str,
    pub ty: FieldTy,
    // LP64 / ILP32。コメント文字列だけ long 幅で位置が異なる。
    pub offset: [usize; 2],
}
impl LegacyField {
    const fn new(name: &'static str, ty: FieldTy, lp64: usize, ilp32: usize) -> Self {
        Self {
            name,
            ty,
            offset: [lp64, ilp32],
        }
    }

    pub fn at(&self, enc: &SourceEncoding) -> usize {
        self.offset[usize::from(enc.abi.long_bytes == 4)]
    }
}
#[derive(Clone, Copy, Debug)]
pub(crate) struct LegacyStruct {
    pub size: usize,
    pub fields: &'static [LegacyField],
}
impl LegacyStruct {
    pub fn field(&self, name: &str) -> Option<&'static LegacyField> {
        self.fields.iter().find(|f| f.name == name)
    }
}
#[derive(Debug)]
pub(crate) struct LegacyLayout {
    pub magic: u16,
    pub prefix: usize,
    pub irq_count: u32,
    pub header: LegacyStruct,
    pub stats: LegacyStruct,
    pub cpu: LegacyStruct,
    pub serial: LegacyStruct,
    pub net: LegacyStruct,
    pub irqcpu: LegacyStruct,
    pub disk: LegacyStruct,
    pub comment: LegacyStruct,
    pub flags: &'static [(&'static str, u32)],
}
impl LegacyLayout {
    pub fn flag(&self, name: &str) -> u32 {
        self.flags.iter().find(|f| f.0 == name).map_or(0, |f| f.1)
    }
    pub fn cpu_count_is_last_index(&self) -> bool {
        self.magic <= 0x2168
    }
    pub fn disk_requires_flag(&self) -> bool {
        self.magic >= 0x2168
    }
}
pub(crate) fn lookup(magic: u16) -> Option<&'static LegacyLayout> {
    LAYOUTS.iter().find(|l| l.magic == magic)
}
